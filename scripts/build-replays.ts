/**
 * Solves every level with the verifier and stores the winning input timeline.
 * The game uses these as the autopilot for the live menu backdrop.
 *   npm run replays
 */
import { writeFileSync } from 'node:fs';
import { replay, solve } from '../src/game/dev/solver.ts';
import { VERIFY } from '../src/game/dev/verify.ts';
import { LEVEL_IDS, getLevel } from '../src/game/levels/index.ts';

const out: Record<string, number[]> = {};
for (const id of LEVEL_IDS) {
  const level = getLevel(id);
  const r = solve(level, { ...VERIFY[id], maxNodes: 3_000_000 });
  if (!r.ok) throw new Error(`${id}: unsolved (reached beat ${r.maxBeat.toFixed(1)} — ${r.death})`);
  const check = replay(level, r.toggles);
  if (!check.won || check.shards !== 7) throw new Error(`${id}: replay diverged`);
  out[id] = r.toggles;
  console.log(`${id.padEnd(10)} ${r.toggles.length} inputs, ${r.nodes} nodes`);
}

const body = Object.entries(out)
  .map(([id, t]) => `  ${id}: [${t.join(',')}],`)
  .join('\n');
writeFileSync(
  new URL('../src/game/levels/replays.ts', import.meta.url),
  `// Generated by scripts/build-replays.ts — do not edit by hand.\n` +
  `// Input toggle ticks (240 Hz) of a verified full-shard run for each level.\n` +
  `export const REPLAYS: Record<string, number[]> = {\n${body}\n};\n`,
);
