/**
 * Finds the remix orders the daily remix draws from and stores them.
 *   npm run remixes
 *
 * A remix plays the parts of a track in a different order. An order is kept
 * only when both of these hold:
 *   - the track's reference run, rearranged the same way, still clears the
 *     remix with all three shards (so the game has a run to preview it with);
 *   - the verifier clears it inside the track's timing budget (so the joins
 *     are fair to a human, not just to a replay).
 * Run it again after `npm run replays` whenever a level or the physics change.
 */
import { writeFileSync } from 'node:fs';
import { replay, solve } from '../src/game/dev/solver.ts';
import { VERIFY } from '../src/game/dev/verify.ts';
import { LEVEL_IDS, getLevel } from '../src/game/levels/index.ts';
import { entriesOf, partsOf, remixLevel, remixReplay } from '../src/game/levels/remix.ts';
import { REPLAYS } from '../src/game/levels/replays.ts';
import { getSong } from '../src/game/music/songs.ts';

/** Orders kept per track. */
const KEEP = 20;
/** Orders tried per track before giving up. */
const TRIES = 4000;

function rng(seed: number): () => number {
  let s = seed >>> 0;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = Math.imul(s ^ (s >>> 15), 1 | s);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const out: Record<string, string[]> = {};
LEVEL_IDS.forEach((id, li) => {
  const source = getLevel(id);
  const parts = partsOf(source, getSong(source.meta.song));
  if (parts.length > 10) throw new Error(`${id}: more than ten parts; orders are stored one digit per part`);
  const entries = entriesOf(source, REPLAYS[id], parts);
  const n = parts.length;
  const rand = rng(0x9e3779b9 ^ (li * 7919));
  const seen = new Set<string>();
  // Candidates that keep fewer of the original neighbours are tried first: they are the ones that feel rearranged.
  const candidates: { order: number[]; kept: number }[] = [];
  for (let t = 0; t < TRIES * 4 && candidates.length < TRIES; t++) {
    const mid = Array.from({ length: n - 2 }, (_, i) => i + 1);
    for (let i = mid.length - 1; i > 0; i--) {
      const j = Math.floor(rand() * (i + 1));
      [mid[i], mid[j]] = [mid[j], mid[i]];
    }
    const order = [0, ...mid, n - 1];
    const key = order.join('');
    if (seen.has(key)) continue;
    seen.add(key);
    let kept = 0;
    for (let i = 1; i < n; i++) if (order[i] === order[i - 1] + 1) kept++;
    if (kept === n - 1) continue; // the track as it is
    candidates.push({ order, kept });
  }
  candidates.sort((a, b) => a.kept - b.kept);

  const good: string[] = [];
  let tried = 0;
  for (const c of candidates) {
    if (good.length >= KEEP) break;
    tried++;
    const level = remixLevel(source, parts, entries, c.order, { ...source.meta, id: 'daily' });
    const run = replay(level, remixReplay(source, REPLAYS[id], parts, c.order));
    if (!run.won || run.shards !== 7) continue;
    if (!solve(level, { ...VERIFY[id], maxNodes: 300_000 }).ok) continue;
    good.push(c.order.join(''));
  }
  if (good.length === 0) throw new Error(`${id}: no remix order survives`);
  out[id] = good;
  console.log(`${id.padEnd(10)} ${n} parts, ${good.length} orders kept of ${tried} tried`);
});

const body = Object.entries(out)
  .map(([id, orders]) => `  ${id}: [${orders.map((o) => `'${o}'`).join(', ')}],`)
  .join('\n');
writeFileSync(
  new URL('../src/game/levels/remixes.ts', import.meta.url),
  `// Generated by scripts/build-remixes.ts — do not edit by hand.\n` +
  `// Orders in which the parts of each track can be replayed: one digit per part, first and last in place.\n` +
  `// Every order was cleared by the rearranged reference run and by the verifier.\n` +
  `export const REMIXES: Record<string, string[]> = {\n${body}\n};\n`,
);
